#!/usr/bin/env node
// Turns web/page.html into arduino/page.h, the page the DEVICE serves itself.
// Both flash scripts run this, so the page you edit is the page you get.
//   node tools/build-page.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(join(root, 'web/page.html'), 'utf8');

if (html.includes(')HTML"')) throw new Error('page.html contains )HTML" - it would end the C++ raw string early');
writeFileSync(join(root, 'arduino/page.h'),
  `// GENERATED by tools/build-page.mjs from web/page.html - do not edit.
#pragma once
const char PAGE[] PROGMEM = R"HTML(${html})HTML";
`);
console.log(`arduino/page.h: ${Math.round(html.length / 1024)} KB page`);
