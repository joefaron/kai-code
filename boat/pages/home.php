<section>
  <h2>The teacher's criteria &mdash; and how we hit each one</h2>
  <table class="crit">
    <tr><th>Criteria</th><th>Our answer</th></tr>
    <tr><td>Must float independently</td><td>Closed-cell foam + sealed bottles in the hull: it floats even if it fills with water</td></tr>
    <tr><td>Must move through the water</td><td>Two air propellers (differential thrust &mdash; spin one faster to turn, like a tank)</td></tr>
    <tr><td>Homemade, not a purchased toy</td><td>Hull is cut and built by Kai and a friend; the electronics are components he wires himself, not an RC boat out of a box</td></tr>
    <tr><td>Household / recycled materials</td><td>Corrugated plastic sign or 2L bottles + foam board hull, bamboo skewers, hot glue</td></tr>
    <tr><td>Nothing left in the ocean</td><td><strong>Zero submerged parts.</strong> No shaft seal to leak, no motor to flood, no oil. Electronics ride in a screw-top food container above deck, leashed with fishing line as a backup</td></tr>
    <tr><td>Explain the design</td><td>This site is the explanation &mdash; see <a href="/?p=design">Design</a></td></tr>
    <tr><td>Test and improve before the beach</td><td>Pool / bathtub trials logged on the <a href="/?p=log">Build Log</a></td></tr>
  </table>
</section>

<section class="callout">
  <h3>&#9888;&#65039; The honest risk</h3>
  <p>Electronics + saltwater is the #1 way this project dies on the sand. That is exactly
  why the design puts <em>nothing</em> underwater and treats the battery box as the only
  thing that must stay dry. The fallback is built in too: if the electronics fail at the
  beach, the same hull still floats and can be sail- or balloon-powered for the race. The
  boat should never depend on the code working.</p>
</section>
